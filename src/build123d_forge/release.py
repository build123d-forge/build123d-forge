"""Automated release packaging, asset bundling, SHA256 checksums, and release notes generator."""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
import shutil
import tomllib
from typing import Any
import zipfile


def compute_file_sha256(path: Path | str) -> str:
    """Compute hex-encoded SHA-256 digest of a file in 64 KiB chunks."""
    target = Path(path)
    hasher = hashlib.sha256()
    with target.open("rb") as f:
        while chunk := f.read(65536):
            hasher.update(chunk)
    return hasher.hexdigest()


def get_project_name(root_dir: Path) -> str:
    """Extract project name from pyproject.toml or fall back to directory name."""
    pyproject = root_dir / "pyproject.toml"
    if pyproject.is_file():
        try:
            data = tomllib.loads(pyproject.read_text(encoding="utf-8"))
            name = data.get("project", {}).get("name")
            if name and isinstance(name, str) and name.strip():
                return name.strip()
        except Exception:
            pass
    return root_dir.name or "build123d-forge"


def generate_release_notes(
    tag: str,
    repo_name: str,
    variants: list[str],
    variant_manifests: dict[str, dict[str, Any] | None],
    variant_assets: dict[str, list[str]],
    zip_names: dict[str, str],
) -> str:
    """Generate visual Markdown release notes with metrics, parameters, and direct download links."""
    lines: list[str] = [
        f"# Release {tag}",
        "",
        f"Automated release assets for **{repo_name}** generated by `build123d-forge`.",
        "",
        "## Quick Downloads",
        "",
        "| Variant | Archive (.zip) | Ready-to-Print STL | STEP CAD |",
        "| :--- | :--- | :--- | :--- |",
    ]

    for var in variants:
        zip_file = zip_names.get(var, f"{var}.zip")
        assets = variant_assets.get(var, [])
        print_stl = next((a for a in assets if a.endswith("_print.stl")), None)
        std_stl = next((a for a in assets if a.endswith(".stl") and not a.endswith("_print.stl")), None)
        step_file = next((a for a in assets if a.endswith(".step") or a.endswith(".stp")), None)

        print_link = f"[{print_stl}]({print_stl})" if print_stl else (f"[{std_stl}]({std_stl})" if std_stl else "—")
        step_link = f"[{step_file}]({step_file})" if step_file else "—"
        lines.append(f"| **`{var}`** | [{zip_file}]({zip_file}) | {print_link} | {step_link} |")

    lines.extend(["", "---", "", "## Variants & Visual Previews", ""])

    for var in variants:
        zip_file = zip_names.get(var, f"{var}.zip")
        assets = variant_assets.get(var, [])
        manifest = variant_manifests.get(var)

        lines.append(f"### Variant: `{var}`")
        lines.append("")

        # Visual preview grid link
        preview_grid = next((a for a in assets if "preview_grid" in a.lower()), None)
        if preview_grid:
            lines.append(f"![{var} Preview Grid]({preview_grid})")
            lines.append("")
        else:
            first_png = next((a for a in assets if a.lower().endswith(".png")), None)
            if first_png:
                lines.append(f"![{var} Preview]({first_png})")
                lines.append("")

        # Geometry metrics from manifest
        if manifest and "metrics" in manifest and isinstance(manifest["metrics"], dict):
            m = manifest["metrics"]
            bb = m.get("bounding_box_mm", (0, 0, 0))
            if isinstance(bb, (list, tuple)) and len(bb) >= 3:
                bb_str = f"{bb[0]:.2f} × {bb[1]:.2f} × {bb[2]:.2f} mm"
            else:
                bb_str = str(bb)

            lines.append("#### Geometry & Verification Metrics")
            lines.append(f"- **Watertight Solid:** {'✅ Yes' if m.get('watertight') else '❌ No'}")
            lines.append(f"- **Solids Count:** {m.get('solids', 1)}")
            lines.append(f"- **Total Faces:** {m.get('faces', 'N/A')}")
            lines.append(f"- **Volume:** {m.get('volume_mm3', 0.0):.2f} mm³")
            lines.append(f"- **Bounding Box (X × Y × Z):** {bb_str}")
            lines.append("")

        # Resolved parameters from manifest
        if manifest:
            params = manifest.get("resolved_params") or manifest.get("parameters")
            if params and isinstance(params, dict):
                lines.append("#### Configuration Parameters")
                lines.append("| Parameter | Value |")
                lines.append("| :--- | :--- |")
                for k, v in sorted(params.items()):
                    lines.append(f"| `{k}` | `{v}` |")
                lines.append("")

        # Direct asset download list
        lines.append("#### Asset Downloads")
        lines.append(f"- 📦 **Complete Bundle:** [{zip_file}]({zip_file})")
        for asset in assets:
            if asset.endswith("_print.stl"):
                lines.append(f"- 🖨️ **Print-Oriented STL:** [{asset}]({asset})")
            elif asset.endswith(".stl"):
                lines.append(f"- 📐 **Standard STL:** [{asset}]({asset})")
            elif asset.endswith(".step") or asset.endswith(".stp"):
                lines.append(f"- 💾 **STEP CAD File:** [{asset}]({asset})")
        lines.extend(["", "---", ""])

    lines.extend([
        "## Checksums & Integrity",
        "",
        "Verify all release assets using the included `SHA256SUMS.txt`:",
        "```bash",
        "sha256sum -c SHA256SUMS.txt",
        "```",
        "",
    ])
    return "\n".join(lines)


def package_release(
    dist_dir: Path | str = "dist",
    out_dir: Path | str = "release_assets",
    tag: str = "",
    repo_name: str | None = None,
) -> Path:
    """Bundle per-variant archives, flattened release assets, SHA256SUMS.txt, and RELEASE_NOTES.md.

    Args:
        dist_dir: Path to built dist directory.
        out_dir: Output directory where release artifacts will be assembled.
        tag: Release tag identifier (e.g. 'v1.0.0').
        repo_name: Optional repository/project name override.

    Returns:
        Path to the prepared output directory.

    Raises:
        ValueError: If tag is missing or empty.
        FileNotFoundError: If dist_dir does not exist or contains no variants.
    """
    if not tag or not tag.strip():
        raise ValueError("Release tag cannot be empty. Specify --tag <TAG>.")

    clean_tag = tag.strip()
    dist_path = Path(dist_dir).resolve()
    if not dist_path.is_dir():
        raise FileNotFoundError(f"Dist directory '{dist_dir}' does not exist.")

    # Discover built variant directories, strictly ignoring schemas/ and hidden dirs
    variant_dirs = [
        d for d in sorted(dist_path.iterdir())
        if d.is_dir() and d.name != "schemas" and not d.name.startswith(".")
    ]
    if not variant_dirs:
        raise FileNotFoundError(f"No built variant directories found in '{dist_dir}'. Run 'bforge build' first.")

    out_path = Path(out_dir).resolve()
    out_path.mkdir(parents=True, exist_ok=True)

    if repo_name is None or not repo_name.strip():
        repo_name = get_project_name(dist_path.parent)

    variant_manifests: dict[str, dict[str, Any] | None] = {}
    variant_assets: dict[str, list[str]] = {}
    zip_names: dict[str, str] = {}
    variants: list[str] = []

    # Flattened asset file extensions
    ASSET_EXTENSIONS = {".stl", ".step", ".stp", ".png", ".svg", ".3mf"}

    for var_dir in variant_dirs:
        var_name = var_dir.name
        variants.append(var_name)
        zip_name = f"{var_name}.zip"
        zip_names[var_name] = zip_name
        zip_path = out_path / zip_name

        var_files = [f for f in sorted(var_dir.rglob("*")) if f.is_file()]

        # 1. Bundle per-variant zip archive
        with zipfile.ZipFile(zip_path, "w", compression=zipfile.ZIP_DEFLATED) as zf:
            for f in var_files:
                arcname = f.relative_to(var_dir)
                zf.write(f, arcname=str(arcname))

        # 2. Flatten release assets (<variant>__<asset>)
        flat_asset_names: list[str] = []
        for f in var_files:
            if f.suffix.lower() in ASSET_EXTENSIONS:
                flat_name = f"{var_name}__{f.name}"
                dest = out_path / flat_name
                shutil.copy2(f, dest)
                flat_asset_names.append(flat_name)
        variant_assets[var_name] = flat_asset_names

        # 3. Read manifest if present
        manifest_path = var_dir / "manifest.json"
        if manifest_path.is_file():
            try:
                manifest_data = json.loads(manifest_path.read_text(encoding="utf-8"))
                variant_manifests[var_name] = manifest_data
            except Exception:
                variant_manifests[var_name] = None
        else:
            variant_manifests[var_name] = None

    # 4. Generate RELEASE_NOTES.md
    notes_content = generate_release_notes(
        tag=clean_tag,
        repo_name=repo_name,
        variants=variants,
        variant_manifests=variant_manifests,
        variant_assets=variant_assets,
        zip_names=zip_names,
    )
    (out_path / "RELEASE_NOTES.md").write_text(notes_content, encoding="utf-8")

    # 5. Generate SHA256SUMS.txt
    # Collect all release files in out_path except SHA256SUMS.txt and RELEASE_NOTES.md
    release_files = sorted(
        [
            f for f in out_path.iterdir()
            if f.is_file() and f.name not in {"SHA256SUMS.txt", "RELEASE_NOTES.md"}
        ],
        key=lambda x: x.name,
    )

    lines: list[str] = []
    for f in release_files:
        digest = compute_file_sha256(f)
        lines.append(f"{digest}  {f.name}\n")

    (out_path / "SHA256SUMS.txt").write_text("".join(lines), encoding="utf-8")
    return out_path
